  var root = document.documentElement;
  var nodes = Array.prototype.slice.call(document.querySelectorAll('[data-i18n]'));
  var EN = {};
  nodes.forEach(function (n) { EN[n.dataset.i18n] = n.innerHTML; });

  function save(key, value) { try { localStorage.setItem(key, value); } catch (e) {} }

  function applyLang(lang) {
    var dict = lang === 'ru' ? RU : EN;
    nodes.forEach(function (n) {
      var v = dict[n.dataset.i18n];
      if (v === undefined) v = EN[n.dataset.i18n];
      n.innerHTML = v;
    });
    root.lang = lang;
    var btn = document.getElementById('lang-switch');
    btn.textContent = lang === 'ru' ? 'EN' : 'RU';
    btn.setAttribute('aria-label', lang === 'ru' ? 'Switch to English' : 'Переключить на русский');
  }

  function applyThemeLabel() {
    var dark = root.dataset.theme === 'dark';
    var btn = document.getElementById('theme-switch');
    var ru = root.lang === 'ru';
    btn.setAttribute('aria-label', dark ? (ru ? 'Светлая тема' : 'Light theme') : (ru ? 'Тёмная тема' : 'Dark theme'));
  }

  document.getElementById('lang-switch').addEventListener('click', function () {
    var next = root.lang === 'ru' ? 'en' : 'ru';
    applyLang(next);
    applyThemeLabel();
    save('c1562.lang', next);
  });

  document.getElementById('theme-switch').addEventListener('click', function () {
    var next = root.dataset.theme === 'dark' ? 'light' : 'dark';
    root.dataset.theme = next;
    applyThemeLabel();
    save('c1562.theme', next);
  });

  applyLang(root.lang === 'ru' ? 'ru' : 'en');
  applyThemeLabel();
